"""File storage for site photos.

``LocalStorage`` keeps files in a folder outside anything the web server serves. Keys are
generated by the server (random hex plus a fixed suffix) and checked against a strict pattern
on every call, so a key can never point outside the storage root. An S3-compatible backend can
implement the same three methods later without touching callers.
"""

import re
from pathlib import Path
from typing import Protocol

KEY_PATTERN = re.compile(r"[0-9a-f]{32}(?:_thumb)?\.jpg")


class Storage(Protocol):
    def save(self, key: str, data: bytes) -> None: ...

    def read(self, key: str) -> bytes: ...

    def delete(self, key: str) -> None: ...


class StorageKeyError(ValueError):
    pass


class LocalStorage:
    def __init__(self, root: str | Path) -> None:
        self.root = Path(root).resolve()

    def _path(self, key: str) -> Path:
        if not KEY_PATTERN.fullmatch(key):
            raise StorageKeyError("Invalid storage key.")
        # Two-level fan-out keeps directories small: ab/abcdef....jpg
        return self.root / key[:2] / key

    def save(self, key: str, data: bytes) -> None:
        path = self._path(key)
        path.parent.mkdir(parents=True, exist_ok=True)
        # Write then rename: a crash never leaves a half-written photo under the real name.
        tmp = path.with_suffix(".part")
        tmp.write_bytes(data)
        tmp.replace(path)

    def read(self, key: str) -> bytes:
        return self._path(key).read_bytes()

    def delete(self, key: str) -> None:
        self._path(key).unlink(missing_ok=True)
